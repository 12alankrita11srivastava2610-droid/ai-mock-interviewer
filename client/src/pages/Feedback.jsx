import {
  Radar,
  Pie,
  Bar,
} from "react-chartjs-2";

import {
  Chart as ChartJS,
  RadialLinearScale,
  PointElement,
  LineElement,
  Filler,
  Tooltip,
  Legend,
  ArcElement,
  CategoryScale,
  LinearScale,
  BarElement,
} from "chart.js";

import jsPDF from "jspdf";

ChartJS.register(
  RadialLinearScale,
  PointElement,
  LineElement,
  Filler,
  Tooltip,
  Legend,
  ArcElement,
  CategoryScale,
  LinearScale,
  BarElement
);

function Feedback() {
  const feedbackData =
    JSON.parse(
      localStorage.getItem("feedback")
    ) || {};

  const {
    technicalScore = 0,
    communicationScore = 0,
    overallScore = 0,
    feedback = "No feedback available",
    strengths = [],
    weaknesses = [],
  } = feedbackData;

  const radarData = {
    labels: [
      "Technical",
      "Communication",
      "Overall",
    ],
    datasets: [
      {
        label: "Performance",
        data: [
          technicalScore,
          communicationScore,
          overallScore,
        ],
        backgroundColor:
          "rgba(168,85,247,0.2)",
        borderColor:
          "rgba(168,85,247,1)",
        borderWidth: 2,
      },
    ],
  };

  const pieData = {
    labels: [
      "Technical",
      "Communication",
    ],
    datasets: [
      {
        data: [
          technicalScore,
          communicationScore,
        ],
        backgroundColor: [
          "#8b5cf6",
          "#06b6d4",
        ],
      },
    ],
  };

  const barData = {
    labels: [
      "Technical",
      "Communication",
      "Overall",
    ],
    datasets: [
      {
        label: "Score",
        data: [
          technicalScore,
          communicationScore,
          overallScore,
        ],
        backgroundColor: [
          "#8b5cf6",
          "#06b6d4",
          "#22c55e",
        ],
      },
    ],
  };

const downloadPDF = () => {
  const pdf = new jsPDF();

  const candidateName =
    localStorage.getItem("userName") ||
    "Candidate";

  const currentDate =
    new Date().toLocaleDateString();

  const recommendation =
    overallScore >= 8
      ? "HIRE"
      : overallScore >= 6
      ? "CONSIDER"
      : "IMPROVE";

  // ===== COVER PAGE =====

  pdf.setFillColor(20, 20, 20);
  pdf.rect(0, 0, 210, 297, "F");

  pdf.setTextColor(255, 255, 255);

  pdf.setFontSize(28);
  pdf.text(
    "AI MOCK INTERVIEW",
    35,
    60
  );

  pdf.setFontSize(22);
  pdf.text(
    "PERFORMANCE REPORT",
    25,
    80
  );

  pdf.setDrawColor(138, 92, 246);
  pdf.setLineWidth(2);
  pdf.line(20, 95, 190, 95);

  pdf.setFontSize(16);

  pdf.text(
    `Candidate: ${candidateName}`,
    20,
    130
  );

  pdf.text(
    `Date: ${currentDate}`,
    20,
    145
  );

  pdf.setFillColor(138, 92, 246);

  pdf.roundedRect(
    20,
    170,
    70,
    35,
    5,
    5,
    "F"
  );

  pdf.setFontSize(14);
  pdf.text(
    "OVERALL SCORE",
    25,
    185
  );

  pdf.setFontSize(20);
  pdf.text(
    `${overallScore}/10`,
    38,
    198
  );

  pdf.setFontSize(11);

  pdf.text(
    "Generated by AI Mock Interviewer",
    20,
    280
  );

  // ===== PAGE 2 =====

  pdf.addPage();

  pdf.setTextColor(0);

  pdf.setFontSize(24);
  pdf.text(
    "Performance Analytics",
    20,
    20
  );

  pdf.setFontSize(14);

  pdf.text(
    `Technical Score: ${technicalScore}/10`,
    20,
    50
  );

  pdf.text(
    `Communication Score: ${communicationScore}/10`,
    20,
    65
  );

  pdf.text(
    `Overall Score: ${overallScore}/10`,
    20,
    80
  );

  // Recommendation Badge

  pdf.setFillColor(
    recommendation === "HIRE"
      ? 34
      : recommendation ===
        "CONSIDER"
      ? 234
      : 220,
    recommendation === "HIRE"
      ? 197
      : recommendation ===
        "CONSIDER"
      ? 179
      : 38,
    recommendation === "HIRE"
      ? 94
      : recommendation ===
        "CONSIDER"
      ? 8
      : 38
  );

  pdf.roundedRect(
    20,
    100,
    60,
    18,
    4,
    4,
    "F"
  );

  pdf.setTextColor(255);

  pdf.text(
    recommendation,
    35,
    112
  );

  pdf.setTextColor(0);

  // Strengths

  pdf.setFontSize(18);
  pdf.text(
    "Strengths",
    20,
    140
  );

  pdf.setFontSize(12);

  strengths.forEach(
    (item, index) => {
      pdf.text(
        `• ${item}`,
        25,
        155 + index * 10
      );
    }
  );

  let y =
    165 +
    strengths.length * 10;

  pdf.setFontSize(18);
  pdf.text(
    "Areas to Improve",
    20,
    y
  );

  pdf.setFontSize(12);

  weaknesses.forEach(
    (item, index) => {
      pdf.text(
        `• ${item}`,
        25,
        y + 15 + index * 10
      );
    }
  );

  // ===== PAGE 3 =====

  pdf.addPage();

  pdf.setFontSize(24);

  pdf.text(
    "AI Feedback",
    20,
    20
  );

  pdf.setFontSize(12);

  const feedbackLines =
    pdf.splitTextToSize(
      feedback,
      170
    );

  pdf.text(
    feedbackLines,
    20,
    45
  );

  pdf.setFontSize(10);

  pdf.text(
    "End of Report",
    20,
    280
  );

  pdf.save(
    `Interview_Report_${candidateName}.pdf`
  );
};

  return (
    <div
      id="feedback-report"
      className="min-h-screen bg-black text-white p-8"
    >
      <div className="max-w-7xl mx-auto">

        <h1 className="text-6xl font-bold text-center mb-10">
          Interview Analytics
        </h1>

        {/* Score Cards */}

        <div className="grid md:grid-cols-3 gap-6 mb-10">

          <div className="bg-gradient-to-r from-purple-700 to-purple-500 p-6 rounded-2xl shadow-lg">
            <h3 className="text-xl">
              Technical Score
            </h3>

            <p className="text-5xl font-bold mt-4">
              {technicalScore}/10
            </p>
          </div>

          <div className="bg-gradient-to-r from-cyan-700 to-cyan-500 p-6 rounded-2xl shadow-lg">
            <h3 className="text-xl">
              Communication Score
            </h3>

            <p className="text-5xl font-bold mt-4">
              {communicationScore}/10
            </p>
          </div>

          <div className="bg-gradient-to-r from-green-700 to-green-500 p-6 rounded-2xl shadow-lg">
            <h3 className="text-xl">
              Overall Score
            </h3>

            <p className="text-5xl font-bold mt-4">
              {overallScore}/10
            </p>
          </div>

        </div>

        {/* Charts */}

        <div className="grid md:grid-cols-2 gap-8 mb-10">

          <div className="bg-zinc-900 p-6 rounded-2xl">
            <h2 className="text-2xl mb-4">
              Radar Analysis
            </h2>

            <Radar data={radarData} />
          </div>

          <div className="bg-zinc-900 p-6 rounded-2xl">
            <h2 className="text-2xl mb-4">
              Performance Split
            </h2>

            <Pie data={pieData} />
          </div>

        </div>

        <div className="bg-zinc-900 p-6 rounded-2xl mb-10">
          <h2 className="text-2xl mb-4">
            Score Breakdown
          </h2>

          <Bar data={barData} />
        </div>

        {/* Strengths */}

        <div className="grid md:grid-cols-2 gap-8 mb-10">

          <div className="bg-green-950 border border-green-700 p-6 rounded-2xl">
            <h2 className="text-3xl mb-4 text-green-400">
              Strengths
            </h2>

            <ul className="space-y-3">
              {strengths.length > 0 ? (
                strengths.map(
                  (item, index) => (
                    <li key={index}>
                      ✅ {item}
                    </li>
                  )
                )
              ) : (
                <li>
                  Strong technical
                  understanding
                </li>
              )}
            </ul>
          </div>

          <div className="bg-red-950 border border-red-700 p-6 rounded-2xl">
            <h2 className="text-3xl mb-4 text-red-400">
              Areas to Improve
            </h2>

            <ul className="space-y-3">
              {weaknesses.length > 0 ? (
                weaknesses.map(
                  (item, index) => (
                    <li key={index}>
                      ⚠️ {item}
                    </li>
                  )
                )
              ) : (
                <li>
                  Improve answer
                  depth and examples
                </li>
              )}
            </ul>
          </div>

        </div>

        {/* AI Feedback */}

        <div className="bg-zinc-900 p-8 rounded-2xl mb-10">
          <h2 className="text-4xl mb-4">
            AI Feedback
          </h2>

          <p className="text-lg leading-8 text-gray-300">
            {feedback}
          </p>
        </div>

        {/* PDF Button */}

        <div className="text-center">
          <button
            onClick={downloadPDF}
            className="bg-purple-600 hover:bg-purple-700 px-8 py-4 rounded-xl text-xl font-bold"
          >
            Download Performance Report PDF
          </button>
        </div>
        <div className="text-center mt-6">
  <button
    onClick={() => navigate("/dashboard")}
    className="bg-blue-600 hover:bg-blue-700 px-8 py-4 rounded-xl text-xl font-bold"
  >
    Back to Dashboard
  </button>
</div>

      </div>
    </div>
  );
}

export default Feedback;